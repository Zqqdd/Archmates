#!/usr/bin/env python3
"""Builds the icons shared by every Archmates front-end from the Tabler icon font (MIT),
the same icons Noctalia draws, so Winmates and the universal widget look like the Noctalia panel:

  assets/icons/archmates-icons.ttf                         font subset, drawn by Winmates (egui)
  desktop/linux/icons/hicolor/scalable/actions/*.svg       symbolic icons for the GTK widget
  src/gui/icons.rs                                         the codepoints, for Winmates

Usage: scripts/make-icons.py [tabler-font.ttf tabler.json]
(default: Noctalia's copy in /usr/share/noctalia/assets/fonts)."""

import json
import shutil
import subprocess
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = Path(sys.argv[1] if len(sys.argv) > 2 else "/usr/share/noctalia/assets/fonts/noctalia-tabler.ttf")
MAP = Path(sys.argv[2] if len(sys.argv) > 2 else "/usr/share/noctalia/assets/fonts/tabler.json")

ICONS = [
    "send", "x", "paperclip", "microphone", "trash", "settings", "player-play-filled", "player-stop-filled",
    "copy", "users", "user", "minus", "chevron-left", "plus", "file-download", "download", "user-plus",
    "check", "alert-circle", "eye-off", "photo",
]

codes = json.loads(MAP.read_text())
font = TTFont(FONT)
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
em = font["head"].unitsPerEm
ascent = font["hhea"].ascent
descent = font["hhea"].descent
height = ascent - descent

svg_dir = ROOT / "desktop/linux/icons/hicolor/scalable/actions"
shutil.rmtree(svg_dir, ignore_errors=True)
svg_dir.mkdir(parents=True)
points = {}
for name in ICONS:
    cp = int(codes[name]["codepoint"].removeprefix("U+"), 16)
    points[name] = cp
    glyph_name = cmap[cp]
    pen = SVGPathPen(glyphs)
    glyphs[glyph_name].draw(pen)
    width = glyphs[glyph_name].width or em
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 {width} {height}">'
           f'<path fill="#000" transform="translate(0 {ascent}) scale(1 -1)" d="{pen.getCommands()}"/></svg>\n')
    (svg_dir / f"archmates-{name}-symbolic.svg").write_text(svg)

assets = ROOT / "assets/icons"
assets.mkdir(parents=True, exist_ok=True)
subprocess.run(["pyftsubset", str(FONT), "--unicodes=" + ",".join(f"U+{cp:04X}" for cp in points.values()),
                f"--output-file={assets / 'archmates-icons.ttf'}", "--layout-features=", "--no-hinting"], check=True)

rust = ["//! Icon codepoints in assets/icons/archmates-icons.ttf (Tabler icons, MIT), the icons Noctalia",
        "//! draws. Generated by scripts/make-icons.py: do not edit.", "", "#![allow(dead_code)]", ""]
for name, cp in points.items():
    rust.append(f"pub const {name.upper().replace('-', '_')}: char = '\\u{{{cp:04x}}}';")
(ROOT / "src/gui/icons.rs").write_text("\n".join(rust) + "\n")
print(f"{len(points)} icons")
